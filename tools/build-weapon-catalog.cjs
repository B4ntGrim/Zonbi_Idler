// Export design references for the display-only weapon catalog. No gameplay imports.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const axeSource = 'handoff/from-design/axe-index-2026-10-24/axe-catalogue-300.json';
const legacySource = 'unity/Assets/Editor/WeaponSeeder.cs';
const axes = JSON.parse(fs.readFileSync(path.join(root, axeSource), 'utf8'));
const allModels = axes.entries;
if (!Array.isArray(allModels) || allModels.length !== axes.counts.models) throw new Error('Axe source count does not match');
if (new Set(allModels.map(m => m.draft_id)).size !== allModels.length) throw new Error('Duplicate axe IDs');
// Sam requested 100 regular axes plus all six named Unique concepts.
const uniqueIds = ['AXE-151','AXE-152','AXE-153','AXE-201','AXE-251','AXE-258'];
const sectionLimits = { C1:17, C2:17, C3:17, C4:17, C5:16, C6:16 };
const regular = axes.categories.flatMap(c => allModels.filter(m => m.catalogue_section === c.id && !uniqueIds.includes(m.draft_id)).slice(0, sectionLimits[c.id]));
const uniques = uniqueIds.map(id => allModels.find(m => m.draft_id === id));
if (regular.length !== 100 || uniques.some(m => !m)) throw new Error('Expected 100 regular axes and all six named Uniques');
const models = [...regular, ...uniques];
const seedText = fs.readFileSync(path.join(root, legacySource), 'utf8');
const pattern = /new WeaponSeed\("([^"]+)",\s*"([^"]+)",\s*WeaponSlot\.(\w+),\s*WeaponKind\.(\w+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)f,\s*(\d+),\s*(?:"([^"]+)"|null),\s*(\d+),\s*(\d+),\s*WeaponStatScaling\.(\w+)\)/g;
const legacy = [...seedText.matchAll(pattern)].map(m => ({
  id:m[1], name:m[2], slot:m[3].toLowerCase(), kind:m[4], damageMin:Number(m[5]), damageMax:Number(m[6]),
  damageMultiplier:Number(m[7]), magazine:Number(m[8]), ammo:m[9] || null, durability:Number(m[10]), sockets:Number(m[11]), scaling:m[12],
}));
if (legacy.length !== 10) throw new Error('Legacy seed schema changed; review the exporter');
const data = { axeSource, legacySource, sourceModelCount:allModels.length, displayModelLimit:100, categories:axes.categories, origins:axes.origins, models, legacy };
const out = '// Generated by node tools/build-weapon-catalog.cjs from the referenced design files.\n'
  + '// Reference records only; never import into loot, saves, inventory, or combat.\n'
  + 'window.ZI_WEAPON_DESIGNS = ' + JSON.stringify(data, null, 0) + ';\n';
fs.writeFileSync(path.join(root, 'weapon-design-data.js'), out);
console.log(`Exported ${regular.length} regular axe designs, ${uniques.length} named Unique concepts and ${legacy.length} legacy prototype records.`);
